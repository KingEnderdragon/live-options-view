class Fixtures(unittest.TestCase):
    def test_fixture_hashes_pinned(self):
        found = {p.relative_to(FIXTURES).as_posix(): hashlib.sha256(p.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
                 for p in FIXTURES.rglob("*") if p.is_file()}
        self.assertEqual(found, FIXTURE_SHA256)

    def test_every_feed_fixture_is_labeled_synthetic(self):
        for p in FIXTURES.rglob("*.xml"):
            if p.parent.name == "parser" and p.name in ("malformed.xml", "entities.xml"):
                continue
            with self.subTest(fixture=p.name):
                self.assertIn(b"SYNTHETIC", p.read_bytes())

    def test_every_price_record_is_labeled_synthetic(self):
        import json
        for p in FIXTURES.rglob("*.jsonl"):
            rows = [json.loads(line) for line in p.read_text(encoding="utf-8").splitlines() if line.strip()]
            with self.subTest(fixture=p.name):
                self.assertIn("SYNTHETIC", rows[0]["label"])
                self.assertTrue(all(r["synthetic"] is True for r in rows))


class Configuration(unittest.TestCase):
    def test_only_the_fixture_backed_subset_is_enabled(self):
        enabled = {s.id for s in config.SOURCES.values() if s.enabled}
        self.assertEqual(enabled, {"oilprice_com", "eia_today_in_energy", "techcrunch", "ars_technica"})
        self.assertEqual({s.id for s in config.enabled_sources()}, enabled)
        self.assertIn("gcaptain", {s.id for s in config.enabled_sources(extra=("gcaptain",))})
        with self.assertRaises(ValueError):
            config.enabled_sources(extra=("not_a_source",))

    def test_pinned_feed_maps_and_shared_sources(self):
        self.assertEqual((len(config.OIL_FEEDS), len(config.AI_FEEDS)), (56, 30))
        self.assertEqual(config.SOURCES["oilprice_com"].url, "https://oilprice.com/rss/main")
        self.assertEqual(config.SOURCES["ars_technica"].url, "http://feeds.arstechnica.com/arstechnica/index")
        for shared in ("eia_today_in_energy", "eia_press_releases", "reddit_r_energy"):
            self.assertEqual(config.SOURCES[shared].streams, ("oil", "ai_buildout"))
        self.assertEqual(len(config.SOURCES), 56 + 30 - 3)

    def test_contract_bounds(self):
        self.assertEqual((config.REQUEST_TIMEOUT_S, config.MAX_RETRIES, config.MAX_CONCURRENT_SOURCES,
                          config.CYCLE_BUDGET_S, config.LATEST_LIMIT), (20, 2, 4, 180, 200))
        self.assertEqual(config.NAMESPACE, "news/v1")

    def test_digests_change_with_rules(self):
        base = config.rules_digest()
        changed = dict(config.STREAMS, oil=config.Stream("oil", "x", ("oil",), "sport", (), ("UNMAPPED",)))
        self.assertNotEqual(base, config.rules_digest(changed))
        self.assertEqual(base, config.rules_digest())


