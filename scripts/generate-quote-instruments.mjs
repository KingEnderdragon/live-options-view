// Generate site/shared/instruments.js from the accepted exact-100 registry.
//
// The browser panel needs identity, display names, units and asset classes for
// pin search and ranking, but it must not fetch the Python registry at runtime.
// This is a deterministic projection of the one canonical source; the web test
// regenerates it and fails when the committed file drifts.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const CORE_LABELS = ['QQQ', 'SPY', 'VIX', '10Y', 'EUR/USD', '/CL', '/GC', 'BTC/USD'];
export const DEFAULT_PINS = ['SMH', 'IGV', 'USO', 'AAPL'];
const FIELDS = ['id', 'label', 'name', 'asset_class', 'instrument_type', 'unit', 'profile', 'change_unit', 'compact'];

export function renderInstruments(universe = JSON.parse(
  readFileSync(new URL('../market_data/overview/universe.json', import.meta.url), 'utf8'))) {
  const rows = {};
  for (const instrument of universe.instruments) {
    const row = {};
    for (const field of FIELDS) row[field] = instrument[field] ?? null;
    rows[instrument.label] = row;
  }
  const body = Object.entries(rows).map(([label, row]) =>
    `  ${JSON.stringify(label)}: ${JSON.stringify(row)},`).join('\n');
  return `// Generated by scripts/generate-quote-instruments.mjs from
// market_data/overview/universe.json. Do not edit by hand; the web test
// regenerates this projection and fails on drift.
'use strict';
const QUOTE_INSTRUMENTS = Object.freeze({
${body}
});
const QUOTE_CORE_LABELS = Object.freeze(${JSON.stringify(CORE_LABELS)});
const QUOTE_DEFAULT_PINS = Object.freeze(${JSON.stringify(DEFAULT_PINS)});
if (typeof module !== 'undefined') {
  module.exports = { QUOTE_INSTRUMENTS, QUOTE_CORE_LABELS, QUOTE_DEFAULT_PINS };
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = fileURLToPath(new URL('../site/shared/instruments.js', import.meta.url));
  writeFileSync(target, renderInstruments());
  console.log(target);
}
